#!/usr/bin/env python3
"""
Injects SEO/social metadata into every page: canonical, Open Graph, Twitter
card and JSON-LD. Idempotent — re-running replaces the block it wrote before.

Run locally after adding a page:  python scripts/inject-meta.py
"""
import os
import re
import json
import html

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = "https://massimojj.github.io/mg-ghanbari"

SKIP_DIRS = {"assets", "scripts", "node_modules", ".git"}
PAGES = ["index.html"]
for d in sorted(os.listdir(ROOT)):
    if d in SKIP_DIRS or not os.path.isdir(os.path.join(ROOT, d)):
        continue
    for f in sorted(os.listdir(os.path.join(ROOT, d))):
        if f.endswith(".html") and f != "404.html":
            PAGES.append(f"{d}/{f}")

HOME_DESC = ("Portfolio of MG Ghanbari — 3D and VFX artist and developer. Character and creature "
             "work, Unreal Engine environments, cinematic animation, AI automation tools and mobile games.")

# Bing Webmaster Tools ownership token (issued 2026-11-04)
BING_VERIFY = "DCE6D02AD86BB082714EB4C5D1438374"

START = "<!-- seo:start (generated by scripts/inject-meta.py) -->"
END = "<!-- seo:end -->"


def slug_for(page):
    return "home" if page == "index.html" else page.replace("/", "-").replace(".html", "")


def url_for(page):
    """Pages are served at pretty URLs (/apps/x), so canonicals must match them."""
    if page == "index.html":
        return BASE + "/"
    if page.endswith("/index.html"):
        return f"{BASE}/{page[:-len('index.html')]}"
    return f"{BASE}/{page[:-5]}"


def read(page):
    return open(os.path.join(ROOT, page), encoding="utf-8", errors="ignore").read()


def build_block(page):
    s = read(page)
    title = re.search(r"<title>(.*?)</title>", s, re.S)
    title = html.unescape(re.sub(r"\s+", " ", title.group(1)).strip()) if title else "MG Ghanbari"

    desc = re.search(r'<meta\s+name="description"\s+content="([^"]*)"', s)
    desc = html.unescape(desc.group(1)).strip() if desc else ""
    if page == "index.html":
        desc = HOME_DESC

    h1 = re.search(r"<h1[^>]*>(.*?)</h1>", s, re.S)
    h1 = html.unescape(re.sub(r"<[^>]+>", "", h1.group(1))).strip() if h1 else title

    url = url_for(page)
    og_img = f"{BASE}/assets/og/{slug_for(page)}.jpg"
    kind = "website" if page == "index.html" else "article"

    person = {
        "@type": "Person",
        "@id": BASE + "/#person",
        "name": "Massimo Javer (MG Ghanbari)",
        "alternateName": "MG Ghanbari",
        "url": BASE + "/",
        "jobTitle": "3D & VFX Artist, Developer",
        "knowsAbout": ["3D modelling", "VFX", "Unreal Engine", "Blender", "ZBrush",
                       "Character animation", "AI automation", "Game development"],
        "sameAs": [
            "https://www.instagram.com/ghammahmoud/",
            "https://www.behance.net/massimojaver_xartist",
            "https://www.artstation.com/massimo83",
            "https://www.linkedin.com/in/massimo-javer-277a16326/",
            "https://www.instagram.com/xartist166/",
            "https://www.instagram.com/kham_comedy/reels/",
            "https://github.com/MassimoJJ",
        ],
    }

    if page == "index.html":
        ld = {
            "@context": "https://schema.org",
            "@graph": [
                person,
                {
                    "@type": "WebSite",
                    "@id": BASE + "/#website",
                    "url": BASE + "/",
                    "name": "MG Ghanbari",
                    "description": desc,
                    "publisher": {"@id": BASE + "/#person"},
                    "inLanguage": "en",
                },
            ],
        }
    else:
        ld = {
            "@context": "https://schema.org",
            "@graph": [
                person,
                {
                    "@type": "CreativeWork",
                    "name": h1,
                    "headline": h1,
                    "description": desc,
                    "url": url,
                    "image": og_img,
                    "creator": {"@id": BASE + "/#person"},
                    "inLanguage": "en",
                    "isPartOf": {"@id": BASE + "/#website"},
                },
                {
                    "@type": "BreadcrumbList",
                    "itemListElement": [
                        {"@type": "ListItem", "position": 1, "name": "Home", "item": BASE + "/"},
                        {"@type": "ListItem", "position": 2, "name": h1, "item": url},
                    ],
                },
            ],
        }

    e = html.escape
    lines = [
        START,
        f'<link rel="canonical" href="{url}">',
        f'<meta name="msvalidate.01" content="{BING_VERIFY}">',
        '<link rel="icon" href="/favicon.ico" sizes="any">',
        '<link rel="icon" type="image/png" href="/favicon.png">',
        '<link rel="apple-touch-icon" href="/apple-touch-icon.png">',
        f'<meta property="og:type" content="{kind}">',
        '<meta property="og:site_name" content="MG Ghanbari">',
        f'<meta property="og:title" content="{e(title)}">',
        f'<meta property="og:description" content="{e(desc)}">',
        f'<meta property="og:url" content="{url}">',
        f'<meta property="og:image" content="{og_img}">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        f'<meta property="og:image:alt" content="{e(h1)}">',
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="twitter:title" content="{e(title)}">',
        f'<meta name="twitter:description" content="{e(desc)}">',
        f'<meta name="twitter:image" content="{og_img}">',
        '<script type="application/ld+json">' + json.dumps(ld, ensure_ascii=False, separators=(",", ":")) + "</script>",
        END,
    ]
    return "\n    ".join(lines), desc, title


def main():
    for page in PAGES:
        path = os.path.join(ROOT, page)
        s = read(page)

        # strip a previously generated block
        s = re.sub(re.escape(START) + r".*?" + re.escape(END) + r"\s*", "", s, flags=re.S)

        block, desc, title = build_block(page)

        if page == "index.html" and not re.search(r'<meta\s+name="description"', s):
            s = s.replace('<meta name="viewport"',
                          f'<meta name="description" content="{html.escape(desc)}">\n    <meta name="viewport"', 1)

        if "</head>" in s:
            s = s.replace("</head>", "    " + block + "\n</head>", 1)
        else:
            print("!! no </head> in", page)
            continue

        open(path, "w", encoding="utf-8").write(s)
        print(f"{page:42} {title[:58]}")


if __name__ == "__main__":
    main()
