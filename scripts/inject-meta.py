#!/usr/bin/env python3
"""
Injects SEO/AEO metadata into every page: canonical, Open Graph, Twitter
card, crawler hints and JSON-LD. Idempotent — re-running replaces the block
it wrote before.

Run locally after adding a page:  python scripts/inject-meta.py
"""
import os
import re
import json
import html
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = "https://massimojj.github.io/mg-ghanbari"

SKIP_DIRS = {"assets", "scripts", "node_modules", ".git"}
PAGES = ["index.html"]
for d in sorted(os.listdir(ROOT)):
    if d in SKIP_DIRS or not os.path.isdir(os.path.join(ROOT, d)):
        continue
    for f in sorted(os.listdir(os.path.join(ROOT, d))):
        if f.endswith(".html") and f != "404.html":
            PAGES.append(f"{d}/{f}")

HOME_DESC = ("Portfolio of MG Ghanbari — 3D and VFX artist and developer. Character and creature "
             "work, Unreal Engine environments, cinematic animation, AI automation tools and mobile games.")

# Bing Webmaster Tools ownership token (issued 2026-11-04)
BING_VERIFY = "DCE6D02AD86BB082714EB4C5D1438374"

START = "<!-- seo:start (generated by scripts/inject-meta.py) -->"
END = "<!-- seo:end -->"


def slug_for(page):
    return "home" if page == "index.html" else page.replace("/", "-").replace(".html", "")


def url_for(page):
    """Pages are served at pretty URLs (/apps/x), so canonicals must match them."""
    if page == "index.html":
        return BASE + "/"
    if page.endswith("/index.html"):
        return f"{BASE}/{page[:-len('index.html')]}"
    return f"{BASE}/{page[:-5]}"


def read(page):
    return open(os.path.join(ROOT, page), encoding="utf-8", errors="ignore").read()


def clean(value):
    return html.unescape(re.sub(r"<[^>]+>", "", value)).strip()


def absolute(href):
    if href.startswith("http://") or href.startswith("https://"):
        return href
    path = href.split("#")[0].split("?")[0]
    if path.endswith(".html"):
        path = path[:-5]
    return BASE + "/" + path.lstrip("/")


def portfolio_items():
    """Read the visible cards on the homepage so structured data matches the UI."""
    s = read("index.html")
    items = []
    for match in re.finditer(r'<a\s([^>]*\bclass="card"[^>]*)>(.*?)</a>', s, re.S | re.I):
        attrs, body = match.group(1), match.group(2)
        href = re.search(r'href="([^"]+)"', attrs, re.I)
        title = re.search(r'<h3[^>]*class="card-title"[^>]*>(.*?)</h3>', body, re.S | re.I)
        desc = re.search(r'<p[^>]*class="card-desc"[^>]*>(.*?)</p>', body, re.S | re.I)
        img = re.search(r'<img[^>]+src="([^"]+)"', body, re.I)
        if not (href and title):
            continue
        items.append({
            "name": clean(title.group(1)),
            "description": clean(desc.group(1)) if desc else "",
            "url": absolute(href.group(1)),
            "image": absolute(img.group(1)) if img else "",
        })
    return items


def faq_items():
    """Read the visible FAQ on the homepage for FAQPage structured data."""
    s = read("index.html")
    items = []
    for match in re.finditer(
        r'<div\s+class="faq-item"\s*>\s*<h3>(.*?)</h3>\s*<p>(.*?)</p>\s*</div>',
        s, re.S | re.I,
    ):
        question = clean(match.group(1))
        answer = clean(match.group(2))
        if question and answer:
            items.append({
                "@type": "Question",
                "name": question,
                "acceptedAnswer": {"@type": "Answer", "text": answer},
            })
    return items


def git_modified(page):
    try:
        out = subprocess.check_output(
            ["git", "log", "-1", "--format=%cI", "--", page],
            cwd=ROOT, stderr=subprocess.DEVNULL, text=True,
        ).strip()
        return out or None
    except Exception:
        return None


def entities_for(page, s):
    """Entity hints taken from terms actually present on the page."""
    haystack = (page + " " + s).lower()
    known = [
        "Unreal Engine", "Blender", "ZBrush", "Marvelous Designer", "Gemini",
        "OpenAI", "Grok", "Replicate", "React", "Capacitor", "Android",
        "motion matching", "VFX", "compositing", "AI automation",
    ]
    return [term for term in known if term.lower() in haystack][:6]


