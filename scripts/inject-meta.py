def build_block(page):
    s = read(page)
    title = re.search(r"<title>(.*?)</title>", s, re.S)
    title = html.unescape(re.sub(r"\s+", " ", title.group(1)).strip()) if title else "MG Ghanbari"

    desc = re.search(r'<meta\s+name="description"\s+content="([^"]*)"', s)
    desc = html.unescape(desc.group(1)).strip() if desc else ""
    if page == "index.html":
        desc = HOME_DESC

    h1 = re.search(r"<h1[^>]*>(.*?)</h1>", s, re.S)
    h1 = clean(h1.group(1)) if h1 else title

    url = url_for(page)
    og_img = f"{BASE}/assets/og/{slug_for(page)}.jpg"
    kind = "website" if page == "index.html" else "article"

    if page == "index.html":
        works = portfolio_items()
        work_items = []
        for i, item in enumerate(works, 1):
            node = {
                "@type": "CreativeWork",
                "name": item["name"],
                "url": item["url"],
                "creator": {"@id": BASE + "/#person"},
                "isPartOf": {"@id": BASE + "/#works"},
            }
            if item["description"]:
                node["description"] = item["description"]
            if item["image"]:
                node["image"] = item["image"]
            work_items.append({
                "@type": "ListItem",
                "position": i,
                "item": node,
            })

        ld = {
            "@context": "https://schema.org",
            "@graph": [
                person_node(),
                {
                    "@type": "WebSite",
                    "@id": BASE + "/#website",
                    "url": BASE + "/",
                    "name": "MG Ghanbari",
                    "description": desc,
                    "publisher": {"@id": BASE + "/#person"},
                    "inLanguage": "en",
                    "potentialAction": {
                        "@type": "SearchAction",
                        "target": BASE + "/?q={search_term_string}",
                        "query-input": "required name=search_term_string",
                    },
                },
                {
                    "@type": "CollectionPage",
                    "@id": BASE + "/#works",
                    "url": BASE + "/#works",
                    "name": "Selected work — VFX, 3D, AI and apps",
                    "description": ("Selected projects by MG Ghanbari: cinematic VFX and composites, "
                                    "character and creature art, Unreal Engine environments, AI film "
                                    "pipelines and shipped mobile/web apps."),
                    "isPartOf": {"@id": BASE + "/#website"},
                    "about": {"@id": BASE + "/#person"},
                    "inLanguage": "en",
                    "mainEntity": {
                        "@type": "ItemList",
                        "numberOfItems": len(work_items),
                        "itemListElement": work_items,
                    },
                },
                {
                    "@type": "Service",
                    "@id": BASE + "/#services",
                    "name": "3D, VFX and AI production",
                    "serviceType": [
                        "VFX compositing", "3D character and creature art",
                        "Character animation", "Unreal Engine environments",
                        "Cinematic animation", "AI production pipelines",
                        "Mobile and web app development",
                    ],
                    "provider": {"@id": BASE + "/#person"},
                    "areaServed": {"@type": "Place", "name": "Worldwide"},
                    "url": BASE + "/#works",
                    "description": ("Available for character art, environment and set work, animation, "
                                    "VFX and simulation, cinematic and game/app work."),
                },
                {
                    "@type": "FAQPage",
                    "@id": BASE + "/#faq",
                    "url": BASE + "/#faq",
                    "name": "Questions people ask about MG Ghanbari",
                    "isPartOf": {"@id": BASE + "/#website"},
                    "mainEntity": faq_items(),
                },
            ],
        }
    else:
        entities = entities_for(page, h1 + " " + desc)
        modified = git_modified(page)
        ld = {
            "@context": "https://schema.org",
            "@graph": [
                person_node(),
                {
                    "@type": "CreativeWork",
                    "@id": url + "#creativework",
                    "name": h1,
                    "headline": h1,
                    "description": desc,
                    "url": url,
                    "image": og_img,
                    "author": {"@id": BASE + "/#person"},
                    "creator": {"@id": BASE + "/#person"},
                    "inLanguage": "en",
                    "isAccessibleForFree": True,
                    "isPartOf": {"@id": BASE + "/#website"},
                },
            ],
        }
        if entities:
            ld["@graph"][1]["keywords"] = ", ".join(entities)
            ld["@graph"][1]["about"] = [
                {"@type": "Thing", "name": term} for term in entities
            ]
        if modified:
            ld["@graph"][1]["dateModified"] = modified
        ld["@graph"].append({
            "@type": "BreadcrumbList",
            "itemListElement": [
                {"@type": "ListItem", "position": 1, "name": "Home", "item": BASE + "/"},
                {"@type": "ListItem", "position": 2, "name": h1, "item": url},
            ],
        })

    e = html.escape
    lines = [
        START,
        f'<link rel="canonical" href="{url}">',
        f'<link rel="alternate" type="text/plain" href="{BASE}/llms.txt" title="LLM-friendly site summary">',
        f'<link rel="alternate" type="text/plain" href="{BASE}/llms-full.txt" title="LLM-friendly full portfolio text">',
        '<meta name="robots" content="index, follow, max-snippet:-1, max-image-preview:large, max-video-preview:-1">',
        f'<meta name="msvalidate.01" content="{BING_VERIFY}">',
        '<link rel="icon" href="/favicon.ico" sizes="any">',
        '<link rel="icon" type="image/png" href="/favicon.png">',
        '<link rel="apple-touch-icon" href="/apple-touch-icon.png">',
        f'<meta property="og:type" content="{kind}">',
        '<meta property="og:site_name" content="MG Ghanbari">',
        '<meta property="og:locale" content="en_US">',
        f'<meta property="og:title" content="{e(title)}">',
        f'<meta property="og:description" content="{e(desc)}">',
        f'<meta property="og:url" content="{url}">',
        f'<meta property="og:image" content="{og_img}">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        f'<meta property="og:image:alt" content="{e(h1)}">',
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="twitter:title" content="{e(title)}">',
        f'<meta name="twitter:description" content="{e(desc)}">',
        f'<meta name="twitter:image" content="{og_img}">',
        '<script type="application/ld+json">' + json.dumps(ld, ensure_ascii=False, separators=(",", ":")) + "</script>",
        END,
    ]
    return "\n    ".join(lines), desc, title


def main():
    for page in PAGES:
        path = os.path.join(ROOT, page)
        s = read(page)

        # strip a previously generated block
        s = re.sub(re.escape(START) + r".*?" + re.escape(END) + r"\s*", "", s, flags=re.S)

        block, desc, title = build_block(page)

        if page == "index.html" and not re.search(r'<meta\s+name="description"', s):
            s = s.replace('<meta name="viewport"',
                          f'<meta name="description" content="{html.escape(desc)}">\n    <meta name="viewport"', 1)

        if "</head>" in s:
            s = s.replace("</head>", "    " + block + "\n</head>", 1)
        else:
            print("!! no </head> in", page)
            continue

        open(path, "w", encoding="utf-8").write(s)
        print(f"{page:42} {title[:58]}")


if __name__ == "__main__":
    main()
